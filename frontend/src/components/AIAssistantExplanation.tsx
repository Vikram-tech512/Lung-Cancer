import React from 'react';
import { Layers, Brain, Flame, Eye, FileText, AlertTriangle, CheckCircle2 } from 'lucide-react';
import { Badge } from './ui/Badge';
import { Panel } from './ui/Panel';

export type XAIMode = 'SEGMENTATION' | 'ATTENTION' | 'GRAD-CAM' | 'SALIENCY';

interface CaseContext {
  id: string;
  name: string;
  verdictClass?: 'MALIGNANT' | 'BENIGN';
  predictedClass?: 'MALIGNANT' | 'BENIGN';
  verdictProb?: number;
  modelScore?: number;
  uncertainty?: string;
  lobe?: string;
  lobeSub?: string;
  anatomicMark?: string;
  area: number;
  compactness: number;
  lobularity?: number;
  cxRel?: number;
  cyRel?: number;
  centroid?: string;
  severity?: string;
  cause?: string;
  pid?: string;
}

interface AIAssistantExplanationProps {
  activeTab: XAIMode;
  onSelectTab?: (tab: XAIMode) => void;
  activeCase?: CaseContext | null;
  currentPixelX?: number | null;
  currentPixelY?: number | null;
}

interface ModalityMetadata {
  title: string;
  badge: string;
  icon: React.FC<any>;
  purpose: string;
  finding: (c: CaseContext, px: number, py: number) => string;
  recommendation: (isMal: boolean) => string;
}

const MODALITY_INFO: Record<XAIMode, ModalityMetadata> = {
  SEGMENTATION: {
    title: 'Volumetric Boundary Delineation',
    badge: '3D V-Net Contour',
    icon: Layers,
    purpose: 'Delineates an algorithmically estimated lesion perimeter. Isolates candidate solid regions from aerated parenchyma. Not a validated lesion boundary unless confirmed by a radiologist.',
    finding: (c, px, py) => {
      const isMal = (c.predictedClass || c.verdictClass) === 'MALIGNANT';
      return `Segmentation mask centered near [${px}, ${py}] in the ${c.lobeSub || c.lobe || 'Right Upper Lobe'}. `
        + `Estimated lesion area: ${(c.area || 13125).toLocaleString()} mm². `
        + `Margin character: ${(c.lobularity || 0.4) > 0.25 ? 'irregular (spiculated appearance)' : 'smooth and circumscribed'}. `
        + `${isMal ? 'Model output: High Suspicion.' : 'Model output: Low Suspicion.'} `
        + 'This is a model-estimated boundary for research review only.';
    },
    recommendation: (_isMal) =>
      'Research use only. All segmentation findings require review by a licensed radiologist. Do not use for standalone surgical planning.',
  },
  ATTENTION: {
    title: 'Multi-Head Self-Attention Rollout',
    badge: '3D Swin Transformer',
    icon: Brain,
    purpose: 'Visualizes internal token routing across local 3D attention windows. Weights denote regional information aggregation.',
    finding: (c, px, py) => {
      const score = c.modelScore ?? c.verdictProb ?? 50;
      return `Attention accumulation centered near [${px}, ${py}] in the ${c.lobe || 'Right Upper Lobe'}. `
        + `Model prediction score: ${score}%. `
        + 'Denotes internal layer routing; requires anatomical verification.';
    },
    recommendation: (_isMal) =>
      'Research use only. Attention rollout reflects architectural weights, not anatomical evidence.',
  },
  'GRAD-CAM': {
    title: 'Gradient-Weighted Class Activation',
    badge: 'Deep Layer Attribution',
    icon: Flame,
    purpose: 'Coarse spatial attribution map generated by weighting feature activations with class-specific backpropagated gradients.',
    finding: (c, px, py) => {
      const cls = c.predictedClass || c.verdictClass || 'MALIGNANT';
      return `Grad-CAM attribution peak near [${px}, ${py}] for candidate class: ${cls}. `
        + 'Resolution is bounded by the bottleneck feature map dimensions and upsampled.';
    },
    recommendation: (_isMal) =>
      'Research use only. Saliency maps are model explanations, not verified lesion boundaries.',
  },
  SALIENCY: {
    title: 'Pixel-Level Gradient Saliency',
    badge: 'Input Gradient Map',
    icon: Eye,
    purpose: 'Measures first-order partial derivatives of the output logit with respect to input voxel intensities.',
    finding: (c, px, py) => {
      const cls = c.predictedClass || c.verdictClass || 'MALIGNANT';
      return `Input gradient saliency localized near [${px}, ${py}] in the ${c.lobe || 'Right Upper Lobe'} for ${cls}.`;
    },
    recommendation: (_isMal) =>
      'Research use only. Input sensitivity gradients are noisy and should not replace radiological inspection.',
  },
};

export const AIAssistantExplanation: React.FC<AIAssistantExplanationProps> = ({
  activeTab,
  onSelectTab,
  activeCase,
  currentPixelX = 195,
  currentPixelY = 168,
}) => {
  if (!activeCase) {
    return (
      <Panel title="Attribution &amp; Explanation Synthesis">
        <div style={{ padding: '24px', textAlign: 'center', color: 'var(--text-muted)', fontSize: '12px' }}>
          No active case selected for attribution synthesis.
        </div>
      </Panel>
    );
  }

  const current = MODALITY_INFO[activeTab] || MODALITY_INFO.SEGMENTATION;
  const isMal = (activeCase.predictedClass || activeCase.verdictClass) === 'MALIGNANT';

  return (
    <Panel
      title="Attribution &amp; Explanation Synthesis"
      subtitle={`Case: ${activeCase.pid || activeCase.name}`}
      actions={
        <Badge variant={isMal ? 'danger' : 'success'}>
          {isMal ? 'High Suspicion' : 'Low Suspicion'}
        </Badge>
      }
    >
      <div style={{ display: 'flex', flexDirection: 'column', gap: '10px' }}>
        {/* Modality Tabs */}
        {onSelectTab && (
          <div style={{ display: 'flex', gap: '4px', borderBottom: '1px solid var(--border)', paddingBottom: '8px' }}>
            {(['SEGMENTATION', 'ATTENTION', 'GRAD-CAM', 'SALIENCY'] as const).map(tab => (
              <button
                key={tab}
                onClick={() => onSelectTab(tab)}
                style={{
                  padding: '4px 8px',
                  borderRadius: 'var(--radius)',
                  border: `1px solid ${activeTab === tab ? 'var(--accent)' : 'var(--border)'}`,
                  background: activeTab === tab ? 'rgba(59, 130, 196, 0.12)' : 'var(--bg-main)',
                  color: activeTab === tab ? 'var(--text-main)' : 'var(--text-muted)',
                  fontSize: '11px',
                  fontWeight: 600,
                  cursor: 'pointer',
                }}
              >
                {tab}
              </button>
            ))}
          </div>
        )}

        {/* Findings block */}
        <div style={{ background: 'var(--bg-main)', border: '1px solid var(--border)', borderRadius: 'var(--radius)', padding: '10px' }}>
          <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: '6px' }}>
            <span style={{ fontSize: '11px', fontWeight: 600, color: 'var(--accent)' }}>
              {current.title}
            </span>
            <Badge variant="neutral">{current.badge}</Badge>
          </div>
          <div style={{ fontSize: '12px', lineHeight: '1.5', color: 'var(--text-main)' }}>
            {current.finding(activeCase, currentPixelX || 195, currentPixelY || 168)}
          </div>
        </div>

        {/* Clinical Advisory notice */}
        <div style={{ display: 'flex', alignItems: 'center', gap: '8px', fontSize: '11px', color: 'var(--text-muted)', background: 'var(--bg-main)', border: '1px solid var(--border)', padding: '8px 10px', borderRadius: 'var(--radius)' }}>
          <AlertTriangle size={13} style={{ color: 'var(--status-warning)', flexShrink: 0 }} />
          <span>{current.recommendation(isMal)}</span>
        </div>
      </div>
    </Panel>
  );
};

export default AIAssistantExplanation;
